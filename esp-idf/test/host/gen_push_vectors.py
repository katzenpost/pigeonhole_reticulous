"""Prints vectors/pigeonhole/push_vectors.json from a pigeonhole_rns checkout: push's subscribe
query and replies, and boxes pushed as Channel messages, encoded by pigeonhole_rns itself.
Needs RNS and hpqc: python3 gen_push_vectors.py PIGEONHOLE_RNS_DIR > vectors/pigeonhole/push_vectors.json"""
import json
import subprocess
import sys

sys.path.insert(0, sys.argv[1])
import RNS  # noqa: E402
from hpqc.bacap.stateless import WriteCap  # noqa: E402
from pigeonhole_rns import PIGEONHOLE_CTX, channel, push, wire  # noqa: E402
from pigeonhole_rns.client import pad, position  # noqa: E402

h = bytes.hex
w = WriteCap.generate()
# A Channel message, as rnsd hands it over: msgtype, then the frame.
piece = RNS.Link.MDU - 6 - channel.HEADER.size


def messages(request_id, data):
    return [h(push_msgtype + f.pack()) for f in channel.split(request_id, data, piece, channel.PushFrame)]


push_msgtype = channel.PushFrame.MSGTYPE.to_bytes(2, "big")
boxes = []
for n, (text, size) in enumerate([(b"pushed at the mesh size", wire.BOX_PLAINTEXT_MESH),
                                   (b"pushed at the mixnet size", wire.BOX_PLAINTEXT_MIXNET)]):
    pos = position(w, n)
    box_id, ct, sig = pos.encrypt(PIGEONHOLE_CTX, pad(text, size))
    msg = push.encode_push(box_id, wire.Reply(wire.SUCCESS, sig, ct))
    boxes.append({"name": "box-%d" % size, "index": h(pos.index.to_bytes()), "box_id": h(box_id), "plaintext": h(text),
                  "size": size, "message": h(msg), "channel_messages": messages(7 + n, msg)})
pos = position(w, 2)
box_id, _ = pos.tombstone(PIGEONHOLE_CTX)
msg = push.encode_push(box_id, wire.Reply(wire.TOMBSTONE))
boxes.append({"name": "tombstone", "index": h(pos.index.to_bytes()), "box_id": h(box_id), "plaintext": "",
              "size": 0, "message": h(msg), "channel_messages": messages(9, msg)})
sub_id = position(w, 3).box_id(PIGEONHOLE_CTX)
rev = subprocess.run(["git", "-C", sys.argv[1], "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
print(json.dumps({
    "about": "pigeonhole_rns push (README, Push), encoded by pigeonhole_rns %s: a subscribe as a mode 2 query "
             "(op 6, ttl 0 for the longest), its replies, and boxes of the stream read_cap pushed as Channel "
             "messages (msgtype 0x5049, then the frame), cut at the 500 byte MTU's piece size. "
             "Generated by test/host/gen_push_vectors.py." % rev,
    "read_cap": h(w.read_cap().to_bytes()),
    "piece": piece,
    "subscribe": {"box_id": h(sub_id), "ttl": 0, "query": h(bytes([push.SUBSCRIBE]) + push.encode_subscribe(0, [sub_id]))},
    "replies": {"taken": h(push.encode_subscribe_reply(1, push.MAX_TTL)),
                "refused": h(push.encode_subscribe_reply(0, push.MAX_TTL)),
                "invalid": h(wire.encode_reply(wire.INVALID_PAYLOAD))},
    "unsubscribe": h(bytes([push.UNSUBSCRIBE]) + sub_id),
    "pushes": boxes,
}, indent=1))
